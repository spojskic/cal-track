/**
 * Generates idempotent seed SQL from the @cal/core catalogs.
 *
 *   pnpm exec tsx packages/core/scripts/generate-seed-sql.ts            # all three files to stdout
 *   pnpm exec tsx packages/core/scripts/generate-seed-sql.ts --out supabase/seed
 *       -> 001_nutrients.sql, 002_dri_values.sql, 003_exercise_activities.sql
 *
 * Idempotency (the schema has no natural unique key on dri_values, by design):
 *   public.nutrients            ON CONFLICT (code)          -- primary key
 *   public.dri_values           delete + re-insert in the same file (reference data only)
 *   public.exercise_activities  ON CONFLICT (code)          -- primary key
 *
 * dri_values.sex is 'male' | 'female' | 'any'; life_stage is 'normal' | 'pregnant' | 'lactating';
 * ul_scope is 'all' | 'supplement_only' | 'synthetic_only' | 'preformed_only' (or null).
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DRI_TABLE, MET_ACTIVITIES, NUTRIENTS } from '../src';

const HEADER = '-- GENERATED by packages/core/scripts/generate-seed-sql.ts - do not edit by hand.\n';

/** SQL string literal with quote escaping, or `null`. */
function str(value: string | null | undefined): string {
  if (value === null || value === undefined) return 'null';
  return `'${value.replace(/'/g, "''")}'`;
}

/** SQL numeric literal, or `null`. */
function num(value: number | null | undefined): string {
  if (value === null || value === undefined) return 'null';
  if (!Number.isFinite(value)) throw new Error(`Non-finite number in seed data: ${value}`);
  return String(value);
}

const bool = (value: boolean | undefined): string => (value ? 'true' : 'false');

/** SQL int[] literal. */
function intArray(values: readonly number[] | undefined): string {
  return values && values.length > 0 ? `array[${values.join(', ')}]::int[]` : `'{}'::int[]`;
}

export function nutrientsSql(): string {
  const rows = NUTRIENTS.map(
    (n) =>
      `  (${[
        str(n.code),
        str(n.name),
        str(n.shortName),
        str(n.unit),
        str(n.group),
        num(n.fdcId),
        intArray(n.fdcAltIds),
        str(n.offKey),
        num(n.order),
        bool(n.computed),
        bool(n.limitNutrient),
        bool(n.highlight),
      ].join(', ')})`,
  );
  return `${HEADER}
insert into public.nutrients
  (code, name, short_name, unit, nutrient_group, fdc_id, fdc_alt_ids, off_key, sort_order, computed, limit_nutrient, highlight)
values
${rows.join(',\n')}
on conflict (code) do update set
  name = excluded.name,
  short_name = excluded.short_name,
  unit = excluded.unit,
  nutrient_group = excluded.nutrient_group,
  fdc_id = excluded.fdc_id,
  fdc_alt_ids = excluded.fdc_alt_ids,
  off_key = excluded.off_key,
  sort_order = excluded.sort_order,
  computed = excluded.computed,
  limit_nutrient = excluded.limit_nutrient,
  highlight = excluded.highlight;
`;
}

export function driValuesSql(): string {
  const rows = DRI_TABLE.map(
    (r) =>
      `  (${[
        str(r.nutrient),
        str(r.sex),
        num(r.ageMin),
        num(r.ageMax),
        str(r.life),
        num(r.rda),
        num(r.ai),
        num(r.ul),
        str(r.ulScope),
        num(r.cdrr),
      ].join(', ')})`,
  );
  return `${HEADER}
begin;
delete from public.dri_values;
insert into public.dri_values
  (nutrient_code, sex, age_min, age_max, life_stage, rda, ai, ul, ul_scope, cdrr)
values
${rows.join(',\n')};
commit;
`;
}

export function exerciseActivitiesSql(): string {
  const rows = MET_ACTIVITIES.map(
    (a) => `  (${[str(a.code), str(a.name), num(a.met), str(a.category)].join(', ')})`,
  );
  return `${HEADER}
insert into public.exercise_activities
  (code, name, met, category)
values
${rows.join(',\n')}
on conflict (code) do update set
  name = excluded.name,
  met = excluded.met,
  category = excluded.category;
`;
}

function main(argv: readonly string[]): void {
  const files: [string, string][] = [
    ['001_nutrients.sql', nutrientsSql()],
    ['002_dri_values.sql', driValuesSql()],
    ['003_exercise_activities.sql', exerciseActivitiesSql()],
  ];
  const outIdx = argv.indexOf('--out');
  if (outIdx === -1) {
    process.stdout.write(files.map(([, sql]) => sql).join('\n'));
    return;
  }
  const dir = argv[outIdx + 1];
  if (!dir || dir.startsWith('--')) {
    process.stderr.write('Usage: generate-seed-sql.ts [--out <dir>]\n');
    process.exit(1);
  }
  mkdirSync(dir, { recursive: true });
  for (const [name, sql] of files) {
    writeFileSync(join(dir, name), sql, 'utf8');
    process.stderr.write(`wrote ${join(dir, name)}\n`);
  }
}

main(process.argv.slice(2));
